export function inquiryHref(collection?: Collection) {
  const subject = collection
    ? `All in One — ${collection.title}`
    : "All in One — запитване за проект"
  const body = `Здравейте,\n\nИнтересувам се от ${collection ? collection.title.toLowerCase() : "индивидуален проект"}.\n\nМестоположение:\nПриблизителни размери / количество:\nПредпочитан срок:\nТелефон за връзка:\n\nБлагодаря!`
  return `mailto:${contact.email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`
}

